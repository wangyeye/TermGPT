    private static let reverse = Dictionary(translations.sorted { $0.key < $1.key }.map { ($0.value, $0.key) }, uniquingKeysWith: { first, _ in first })
    static func text(_ key: String, language: InterfaceLanguage, preferredLanguages: [String] = Locale.preferredLanguages) -> String {
        let chinese = language.resolved(preferredLanguages: preferredLanguages) == .chinese
        if let english = translations[key] { return chinese ? key : english }
        if let chineseText = reverse[key] { return chinese ? chineseText : key }
        // Translate app-generated interpolated status/error messages without modifying their arguments.
        for (zh, en) in translations where zh.contains("%@") {
            let source = chinese ? en : zh, target = chinese ? zh : en
            let parts = source.components(separatedBy: "%@")
            let pattern = "^" + parts.map(NSRegularExpression.escapedPattern(for:)).joined(separator: "(.*?)") + "$"
            guard let regex = try? NSRegularExpression(pattern: pattern, options: [.dotMatchesLineSeparators]),
                  let match = regex.firstMatch(in: key, range: NSRange(key.startIndex..., in: key)) else { continue }
            let values = (1..<match.numberOfRanges).compactMap { Range(match.range(at: $0), in: key).map { String(key[$0]) } }
            return interpolate(target, values)
        }
        return key
    }
    static func interpolate(_ format: String, _ arguments: [String]) -> String {
        let parts = format.components(separatedBy: "%@")
        return parts.enumerated().map { index, part in part + (index < parts.count - 1 ? (index < arguments.count ? arguments[index] : "%@") : "") }.joined()
    }
}
func L(_ key: String, _ arguments: String...) -> String {
    Localization.interpolate(Localization.text(key, language: Localization.shared.selection), arguments)
