import Foundation
import Combine

enum InterfaceLanguage: String, Codable, CaseIterable {
    case system, english, chinese
    var label: String { switch self { case .system: return L("跟随系统"); case .english: return "English"; case .chinese: return "中文" } }
    func resolved(preferredLanguages: [String] = Locale.preferredLanguages) -> InterfaceLanguage {
        guard self == .system else { return self }
        // Only the first system language determines the fallback; unsupported languages use English.
        return preferredLanguages.first?.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-").first == "zh" ? .chinese : .english
    }
}
